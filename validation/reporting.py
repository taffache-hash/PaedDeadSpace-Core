def write_results_csv(rows: Iterable[ScenarioRow], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=RESULT_FIELDS, extrasaction="raise")
        writer.writeheader()
        writer.writerows(rows)
    return path


def write_summary(rows: list[ScenarioRow], path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    direct = next(row for row in rows if row["scenario_family"] == "pearsall_direct")
    counts = Counter(str(row["scenario_class"]) for row in rows)
    breakdown_by_family = Counter(
        str(row["scenario_family"])
        for row in rows
        if row.get("status") == "model_breakdown"
    )
    breakdown_total = sum(breakdown_by_family.values())

    text = f"""# PaedDeadSpace validation summary

This report was generated by a separate validation layer using the installed,
audited `paeddeadspace` core. It is educational and exploratory, not clinical
decision support.

## Classification of evidence

| Scenario class | Rows |
|---|---:|
| quantitative benchmark endpoint | {counts['quantitative_benchmark']} |
| qualitative directionality check | {counts['directionality_check']} |
| external plausibility reference | {counts['plausibility_reference']} |
| exploratory sensitivity | {counts['exploratory_sensitivity']} |

Pass/fail is used only for the Pearsall rounded endpoint and legitimate
physical-state directionality expectations. Exploratory and reference rows are
`not_assessed`.

Across all scenarios, {breakdown_total} states reach the audited core's
one-compartment model-breakdown boundary (`VD >= VT`): {breakdown_by_family.get('general_grid', 0)}
in the general grid and {breakdown_by_family.get('chau_kwon_plus22', 0)} in the
+22 mL family. They are retained and labelled rather than forced through a
numerical ventilation calculation.

## Pearsall quantitative endpoint benchmark

The published sample uses weight 10 kg, VT 8 mL/kg = 80 mL, patient physiologic
VD/VT 0.30, patient VD 24 mL, baseline RR 20/min, and 30 mL apparatus dead
space, for cumulative VD 54 mL. Pearsall reports a required RR of approximately
43/min to maintain PaCO2 40 mmHg.

The audited core does **not** reimplement Pearsall's absolute PaCO2 / Equation 7
path. Instead, it preserves the sample's baseline alveolar ventilation:
`20 × (80 - 24) = 1120 mL/min`; after apparatus, alveolar VT is `80 - 54 = 26
mL`, giving **{float(direct['rr_required_bpm']):.6f}/min**. This reproduces the
published rounded endpoint (~43/min) but should not be described as an exact
recalculation of Pearsall Equation 7. Endpoint evaluation:
**{str(direct['evaluation']).upper()}**.

The associated 0-55 mL curve is a synthetic sensitivity sweep under the named
Pearsall assumptions. A baseline-calibrated PaCO2 column is included only with
the explicitly supplied baseline of 40 mmHg and is mechanistic, not a clinical
prediction.

## Chau / Kwon +22 mL external context

Chau et al. studied 20 healthy intubated children under 2 years and introduced
a 22 mL airway filter. Restoring ETCO2 to 35 mmHg required a mean RR increase
of **19.8 ± 8.7 breaths/min** and a mean ventilation increase of **1.42 ± 0.38
L/min**. Kwon studied a pediatric HME with reported internal volume 22 mL; HME
removal reduced PaCO2 from **46.1 ± 6.9 to 37.9 ± 4.3 mmHg**, with a larger
effect at lower weight/age.

The runner therefore uses +22 mL only for directionality/body-size scaling. It
does not claim that the two devices have identical functional dead space, and
does not fit or assert exact reproduction of either clinical result.

## Campos neonatal +4 mL context

The source bench simulation used 2, 2.5 and 3 kg neonates, VT 8 mL/kg, RR
40/35/30 per minute, and an added apparatus dead space of 4 mL. The reported
airway-dead-space/VT ratios changed from approximately **0.51→0.68** (2 kg),
**0.43→0.62** (2.5 kg) and **0.38→0.60** (3 kg).

This runner now preserves those source weights, VT, RR and +4 mL apparatus
settings. However, its patient-only VD/VT remains the explicit Pearsall-derived
0.30 sensitivity assumption, so the source airway-VD/VT ratios are retained as
context rather than targets. These rows remain directionality/sensitivity
checks, not exact capnogram, rebreathing, or VD/VT validation.

## General sensitivity grid

The grid spans the pre-specified weights, VT presets and apparatus volumes. Its
patient-only VD/VT = 0.30 is visibly an explicit Pearsall-inherited sensitivity
assumption, not a clinical default. RR 20/min is used only as an arithmetic
normalization. Apparatus geometric/internal volume may differ from effective
functional dead space.

## PROVENTIPED external plausibility reference

Published normocapnic alveolar minute ventilation is approximately **68 ± 21
mL/kg/min**. This remains a cohort-level external plausibility reference only.
No constant is tuned to 68, no model case is constructed to equal it, and no
pass/fail decision is made.

## Interpretation limits

Measured clinical VD/VT may already include apparatus depending on method and
setup. It must not be entered as patient-only VD/VT without scientifically
justified decomposition. Approaching `VD = VT` makes normalized model outputs
diverge; this is a mathematical property of the one-compartment model, not a
clinical threshold or prediction.
"""
    path.write_text(text, encoding="utf-8")
    return path


def _save_line_plot(
    x: list[float],
    y: list[float],
    path: Path,
    xlabel: str,
    ylabel: str,
    title: str,
) -> Path:
    figure, axis = plt.subplots()
    axis.plot(x, y)
    axis.set_xlabel(xlabel)
    axis.set_ylabel(ylabel)
    axis.set_title(title)
    figure.tight_layout()
    figure.savefig(path)
    plt.close(figure)
    return path


def _save_pearsall_plots(rows: list[ScenarioRow], output_dir: Path) -> list[Path]:
    selected = [
        row for row in rows if row["scenario_family"] == "pearsall_sensitivity"
    ]
    x = [float(row["apparatus_ds_ml"]) for row in selected]
    return [
        _save_line_plot(
            x,
            [float(row["total_vd_vt"]) for row in selected],
            output_dir / "pearsall_total_vd_vt.png",
            "Apparatus dead space (mL)",
            "Total VD/VT",
            "Pearsall sensitivity: total VD/VT",
        ),
        _save_line_plot(
            x,
            [float(row["alveolar_ve_ml_min"]) for row in selected],
            output_dir / "pearsall_alveolar_ventilation.png",
            "Apparatus dead space (mL)",
            "Alveolar ventilation at RR 20 (mL/min)",
            "Pearsall sensitivity: alveolar ventilation",
        ),
        _save_line_plot(
            x,
            [float(row["relative_co2_burden"]) for row in selected],
            output_dir / "pearsall_relative_co2.png",
            "Apparatus dead space (mL)",
            "Relative CO2 burden",
            "Pearsall sensitivity: relative CO2 burden",
        ),
        _save_line_plot(
            x,
            [float(row["rr_required_bpm"]) for row in selected],
            output_dir / "pearsall_rr_required.png",
            "Apparatus dead space (mL)",
            "RR required (/min)",
            "Pearsall sensitivity: RR required",
        ),
    ]


def _grid_physical_vt6(rows: list[ScenarioRow]) -> list[ScenarioRow]:
    return [
        row
        for row in rows
        if row["scenario_family"] == "general_grid"
        and float(row["vt_ml_kg"]) == 6.0
        and row["status"] == "physical"
    ]


def _save_grouped_grid_plot(
    rows: list[ScenarioRow],
    path: Path,
    field: str,
    ylabel: str,
    title: str,
) -> Path:
    selected = _grid_physical_vt6(rows)
    figure, axis = plt.subplots()
    for weight in sorted({float(row["weight_kg"]) for row in selected}):
        group = [row for row in selected if float(row["weight_kg"]) == weight]
        group.sort(key=lambda row: float(row["apparatus_ds_ml"]))
        axis.plot(
            [float(row["apparatus_ds_ml"]) for row in group],
            [float(row[field]) for row in group],
            marker="o",
            label=f"{weight:g} kg",
        )
    axis.set_xlabel("Apparatus dead space (mL)")
    axis.set_ylabel(ylabel)
    axis.set_title(title)
    axis.legend()
    figure.tight_layout()
    figure.savefig(path)
    plt.close(figure)
    return path


def _save_apparatus_percent_plot(rows: list[ScenarioRow], path: Path) -> Path:
    selected_volumes = (4.0, 22.0, 55.0)
    selected = [
        row
        for row in rows
        if row["scenario_family"] == "general_grid"
        and float(row["vt_ml_kg"]) == 6.0
        and float(row["apparatus_ds_ml"]) in selected_volumes
    ]
    figure, axis = plt.subplots()
    for volume in selected_volumes:
        group = [row for row in selected if float(row["apparatus_ds_ml"]) == volume]
        group.sort(key=lambda row: float(row["weight_kg"]))
        axis.plot(
            [float(row["weight_kg"]) for row in group],
            [float(row["apparatus_ds_percent_vt"]) for row in group],
            marker="o",
            label=f"{volume:g} mL",
        )
    axis.set_xlabel("Weight (kg)")
    axis.set_ylabel("Apparatus dead space / VT (%)")
    axis.set_title("Apparatus fraction versus weight at VT 6 mL/kg")
    axis.legend()
    figure.tight_layout()
    figure.savefig(path)
    plt.close(figure)
    return path


def write_validation_outputs(rows: list[ScenarioRow], output_dir: Path) -> list[Path]:
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = [
        write_results_csv(rows, output_dir / "validation_results.csv"),
        write_summary(rows, output_dir / "validation_summary.md"),
        *_save_pearsall_plots(rows, output_dir),
        _save_grouped_grid_plot(
            rows,
            output_dir / "rr_multiplier_vs_apparatus_vt6.png",
            "rr_multiplier",
            "RR multiplier",
            "RR preservation multiplier at VT 6 mL/kg",
        ),
        _save_grouped_grid_plot(
            rows,
            output_dir / "relative_co2_vs_apparatus_vt6.png",
            "relative_co2_burden",
            "Relative CO2 burden",
            "Relative CO2 burden at VT 6 mL/kg",
        ),
        _save_apparatus_percent_plot(
            rows, output_dir / "apparatus_percent_vt_vs_weight.png"
        ),
    ]
    return paths
